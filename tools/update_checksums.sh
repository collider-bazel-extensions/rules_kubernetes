#!/usr/bin/env bash
# Regenerates the _K8S_VERSIONS block in extensions.bzl from controller-tools'
# envtest releases (kube-apiserver + etcd + kubectl per tarball).
#
# Each tarball is downloaded and verified against the SHA-512 that
# controller-tools publishes next to it (<asset>.sha512); the SHA-256 of the
# verified tarball is what extensions.bzl pins.
#
#   tools/update_checksums.sh           rewrite extensions.bzl
#   tools/update_checksums.sh --check   fail if extensions.bzl differs
#
# To add or bump a version, edit RELEASES below (one envtest release per
# Kubernetes minor) and run the script.
set -euo pipefail

RELEASES=(1.29.0 1.35.0 1.36.2 1.37.0)
PLATFORMS=(linux_amd64 linux_arm64 darwin_arm64 darwin_amd64)
BASE=https://github.com/kubernetes-sigs/controller-tools/releases/download

cd "$(dirname "$0")/.."
check=0
[[ "${1:-}" == "--check" ]] && check=1

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

block="$work/block"
{
  echo "# BEGIN _K8S_VERSIONS (generated by tools/update_checksums.sh)"
  echo "_K8S_VERSIONS = {"
  for release in "${RELEASES[@]}"; do
    minor="${release%.*}"
    echo "    \"$minor\": {"
    echo "        \"release\": \"$release\","
    for platform in "${PLATFORMS[@]}"; do
      asset="envtest-v${release}-${platform/_/-}.tar.gz"
      url="$BASE/envtest-v${release}/${asset}"
      echo "  $asset" >&2
      curl -fsSL -o "$work/$asset" "$url"
      want512="$(curl -fsSL "$url.sha512" | awk '{print $1}')"
      got512="$(sha512sum "$work/$asset" | awk '{print $1}')"
      if [[ "$want512" != "$got512" ]]; then
        echo "SHA-512 mismatch for $asset: published $want512, downloaded $got512" >&2
        exit 1
      fi
      sha256="$(sha256sum "$work/$asset" | awk '{print $1}')"
      rm -f "$work/$asset"
      echo "        \"$platform\": {"
      echo "            \"url\":          \"$url\","
      echo "            \"sha256\":       \"$sha256\","
      echo "            \"strip_prefix\": \"controller-tools/envtest\","
      echo "        },"
    done
    echo "    },"
  done
  echo "}"
  echo "# END _K8S_VERSIONS"
} >"$block"

new="$work/extensions.bzl"
awk -v block="$block" '
  /^# BEGIN _K8S_VERSIONS/ { while ((getline line < block) > 0) print line; skip = 1; next }
  /^# END _K8S_VERSIONS/   { skip = 0; next }
  !skip
' extensions.bzl >"$new"
grep -q '^# BEGIN _K8S_VERSIONS' extensions.bzl || { echo "BEGIN marker missing in extensions.bzl" >&2; exit 1; }

if (( check )); then
  if ! diff -u extensions.bzl "$new"; then
    echo "extensions.bzl is out of date; run tools/update_checksums.sh" >&2
    exit 1
  fi
  echo "extensions.bzl checksums match the published releases"
else
  cp "$new" extensions.bzl
  echo "updated extensions.bzl" >&2
fi
